CREATE TABLE IF NOT EXISTS correo_eventos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 intento_id BIGINT UNSIGNED NOT NULL,
 fase VARCHAR(40) NOT NULL,
 smtp_codigo SMALLINT UNSIGNED NULL,
 message_id VARCHAR(190) NOT NULL,
 detalle VARCHAR(500) NULL,
 creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX (intento_id,id),
 CONSTRAINT fk_correo_evento_intento FOREIGN KEY (intento_id) REFERENCES correo_intentos(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
